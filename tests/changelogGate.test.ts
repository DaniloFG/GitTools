describe('findForbidden: textos ruins reprovam', () => {
  it.each(RUINS)('regra %s reprova "%s"', (regra, texto) => {
    expect(findForbidden(texto).map((a) => a.rule)).toContain(regra)
  })

  it('toda regra da tabela tem ao menos um exemplo ruim acima (nenhuma regra fica sem teste)', () => {
    const cobertas = new Set(RUINS.map(([regra]) => regra))
    for (const { rule } of RULES) expect(cobertas.has(rule), `regra sem teste: ${rule}`).toBe(true)
    // E nenhum exemplo cita uma regra que não existe mais.
    const nomes = new Set(RULES.map((r) => r.rule))
    for (const regra of cobertas) expect(nomes.has(regra), `exemplo de regra inexistente: ${regra}`).toBe(true)
  })

  it('os nomes das regras são únicos', () => {
    expect(new Set(RULES.map((r) => r.rule)).size).toBe(RULES.length)
  })
})

