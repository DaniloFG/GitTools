describe('findForbidden: textos ruins reprovam', () => {
  it.each(RUINS)('regra %s reprova "%s"', (regra, texto) => {
    expect(findForbidden(texto).map((a) => a.rule)).toContain(regra)
  })

  it('toda regra da tabela tem ao menos um exemplo ruim acima (nenhuma regra fica sem teste)', () => {
    const cobertas = new Set(RUINS.map(([regra]) => regra))
    for (const { rule } of RULES) expect(cobertas.has(rule), `regra sem teste: ${rule}`).toBe(true)
    // E nenhum exemplo cita uma regra que não existe mais.
    const nomes = new Set(RULES.map((r) => r.rule))
    for (const regra of cobertas) expect(nomes.has(regra), `exemplo de regra inexistente: ${regra}`).toBe(true)
  })

  it('os nomes das regras são únicos', () => {
    expect(new Set(RULES.map((r) => r.rule)).size).toBe(RULES.length)
  })
})

// Frases em inglês que a revisão achou passando; cada uma precisa reprovar, com ou sem o "- " do bullet.
const FRASES_EM_INGLES = [
  'Archived the sessions',
  'Written by the model',
  'Passed internal validation',
  'Fixed issue 198',
  'Open doubt about the layout',
]

describe('findForbidden: jargão interno em inglês', () => {
  it.each(FRASES_EM_INGLES)('reprova "%s"', (frase) => {
    expect(findForbidden(frase)).not.toEqual([])
    expect(findForbidden(`- ${frase}.`)).not.toEqual([])
  })
})

describe('findForbidden: textos de usuário passam', () => {
  it.each(BONS)('passa "%s"', (texto) => {
    expect(findForbidden(texto)).toEqual([])
  })

  it('siglas só valem em MAIÚSCULAS e palavra inteira', () => {
    expect(findForbidden('mais, ai, ci, pr e qa em minúsculas ficam de fora')).toEqual([])
    expect(findForbidden('PRIMEIRO, CIDADE e AIRBAG não são siglas')).toEqual([])
  })
})

describe('findForbidden: localização e forma', () => {
  it('devolve a linha (a partir de 1), a regra e o trecho', () => {
    const texto = '- Bom.\n- Também bom.\n- Ruim por causa do #12.'
    expect(findForbidden(texto)).toEqual([{ line: 3, rule: 'numero-issue-pr', match: '#12' }])
  })

  it('pega termo dentro de crase, de qualquer caixa, e todas as ocorrências da linha', () => {
    const achados = findForbidden('- Use `PIPELINE` e `Workflow` aqui.')
    expect(achados.map((a) => a.rule)).toEqual(['pipeline', 'workflow'])
  })

  it('aceita fim de linha do Windows', () => {
    expect(findForbidden('- ok\r\n- #3\r\n').map((a) => a.line)).toEqual([2])
  })

  it('pega acento decomposto (NFD) da mesma forma que o composto', () => {
    expect(findForbidden('fábrica').map((a) => a.rule)).toEqual(['fabrica'])
  })

  it('texto vazio não reprova', () => {
    expect(findForbidden('')).toEqual([])
  })
})

const CHANGELOG = `# Changelog

## [Unreleased]

### Added

- Tour of the interface.

## [0.13.0] - 2026-11-11

### Fixed

- Diff windows show their first frame in the saved language.

## [0.12.0] - 2026-11-10

### Added

- Colored diffs.
`

describe('sectionBody', () => {
  it('devolve o texto da seção, sem o cabeçalho e até o próximo "## "', () => {
    const corpo = sectionBody(CHANGELOG, '0.13.0')
    expect(corpo).toContain('### Fixed')
    expect(corpo).toContain('- Diff windows')
    expect(corpo).not.toContain('## [0.13.0]')
    expect(corpo).not.toContain('Colored diffs')
  })

  it('a seção do fim do arquivo vai até o fim', () => {
    expect(sectionBody(CHANGELOG, '0.12.0')).toContain('- Colored diffs.')
  })

  it('devolve null quando a seção não existe', () => {
    expect(sectionBody(CHANGELOG, '9.9.9')).toBeNull()
  })
})

describe('releaseNotes', () => {
  it('usa a seção da versão quando ela existe', () => {
    expect(releaseNotes(CHANGELOG, '0.13.0')).toBe(
      '### Fixed\n\n- Diff windows show their first frame in the saved language.\n',
    )
  })

  it('cai para o Unreleased quando o patch automático não tem seção', () => {
    const notas = releaseNotes(CHANGELOG, '0.13.1')
    expect(notas).toContain('- Tour of the interface.')
    expect(notas.endsWith('\n')).toBe(true)
    expect(notas).not.toContain('Diff windows')
  })

  it('lança erro claro quando nem a versão nem o Unreleased existem', () => {
    expect(() => releaseNotes('# Changelog\n\n## [0.12.0] - 2026-11-10\n\n- Algo.\n', '0.13.1')).toThrow(
      /não tem a seção ## \[0\.13\.1\] nem ## \[Unreleased\]/,
    )
  })

  it('lança erro quando a seção da versão não tem bullet', () => {
    const vazio = CHANGELOG.replace('- Diff windows show their first frame in the saved language.', '')
    expect(() => releaseNotes(vazio, '0.13.0')).toThrow(/## \[0\.13\.0\].*nenhuma mudança/)
  })

  it('lança erro quando o Unreleased tem só "Nothing yet."', () => {
    const nada = CHANGELOG.replace('### Added\n\n- Tour of the interface.', '- Nothing yet.')
    expect(() => releaseNotes(nada, '0.13.1')).toThrow(/## \[Unreleased\].*nenhuma mudança/)
  })

  it('seção da versão vazia não cai para o Unreleased', () => {
    const vazio = CHANGELOG.replace('- Diff windows show their first frame in the saved language.', '')
    expect(() => releaseNotes(vazio, '0.13.0')).toThrow()
  })

  it('recusa versão que não é x.y.z', () => {
    expect(() => releaseNotes(CHANGELOG, 'v0.13.0')).toThrow(/Versão inválida/)
    expect(() => releaseNotes(CHANGELOG, '0.13')).toThrow(/Versão inválida/)
  })
})

// Corpos de release como o "generate_release_notes" escrevia: cada um precisa reprovar.
const CORPOS_SUJOS: [descricao: string, corpo: string][] = [
  ['branch de sessão e seta', '- PR ccr-4ff33997-njtxld → homolog\n'],
  ['fábrica e número de issue', '- encerramento da fábrica paralela (#198)\n'],
  ['autor do release gerado', '- Add the tour by @DaniloFG in https://github.com/dono/GitTools/pull/12\n'],
  ['commit convencional com escopo', '- fix(core): stop the crash\n'],
  ['plano numerado', '- Plano 4\n'],
  ['promoção entre branches', '- Promoção homolog → main\n'],
]

describe('gateProblems', () => {
  it('lista vazia quando Unreleased, seção da versão e corpo estão limpos', () => {
    expect(gateProblems(CHANGELOG, '0.13.0', releaseNotes(CHANGELOG, '0.13.0'))).toEqual([])
    expect(gateProblems(CHANGELOG, '0.13.1', releaseNotes(CHANGELOG, '0.13.1'))).toEqual([])
  })

  it.each(CORPOS_SUJOS)('reprova corpo de release sujo: %s', (_descricao, corpo) => {
    const problemas = gateProblems(CHANGELOG, '0.13.1', corpo)
    expect(problemas.length).toBeGreaterThan(0)
    expect(problemas.every((p) => p.startsWith('Corpo do release, linha 1:'))).toBe(true)
  })

  it('aponta a linha do arquivo, a seção e a regra quando o Unreleased está sujo', () => {
    const sujo = CHANGELOG.replace('- Tour of the interface.', '- Tour of the interface (#12).')
    const linha = sujo.split('\n').findIndex((l) => l.includes('#12')) + 1
    expect(gateProblems(sujo, '0.13.1', 'limpo\n')).toEqual([
      `CHANGELOG [Unreleased], linha ${linha}: termo interno "#12" (regra numero-issue-pr)`,
    ])
  })

  it('confere também a seção da versão, quando ela existe', () => {
    const sujo = CHANGELOG.replace('saved language.', 'saved language, via the pipeline.')
    const problemas = gateProblems(sujo, '0.13.0', 'limpo\n')
    expect(problemas).toHaveLength(1)
    expect(problemas[0]).toMatch(/^CHANGELOG \[0\.13\.0\], linha \d+: .*"pipeline" \(regra pipeline\)$/)
  })

  it('seção já publicada e antiga fica fora (o teste do arquivo inteiro a cobre)', () => {
    const sujo = CHANGELOG.replace('- Colored diffs.', '- Colored diffs (#1).')
    expect(gateProblems(sujo, '0.13.0', 'limpo\n')).toEqual([])
  })
})

describe('prova de mutação: sem as regras, o texto sujo passaria', () => {
  it.each(CORPOS_SUJOS)('com a lista de regras esvaziada, passa: %s', (_descricao, corpo) => {
    expect(findForbidden(corpo)).not.toEqual([])
    expect(findForbidden(corpo, [])).toEqual([])
  })

  it.each(RUINS)('tirar a regra %s da tabela deixa de pegar "%s"', (regra, texto) => {
    const semARegra = RULES.filter((r) => r.rule !== regra)
    expect(findForbidden(texto, semARegra).map((a) => a.rule)).not.toContain(regra)
    expect(findForbidden(texto).map((a) => a.rule)).toContain(regra)
  })
})
