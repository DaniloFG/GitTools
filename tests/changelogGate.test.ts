describe('sectionBody', () => {
  it('devolve o texto da seção, sem o cabeçalho e até o próximo "## "', () => {
    const corpo = sectionBody(CHANGELOG, '0.13.0')
    expect(corpo).toContain('### Fixed')
    expect(corpo).toContain('- Diff windows')
    expect(corpo).not.toContain('## [0.13.0]')
    expect(corpo).not.toContain('Colored diffs')
  })

  it('a seção do fim do arquivo vai até o fim', () => {
    expect(sectionBody(CHANGELOG, '0.12.0')).toContain('- Colored diffs.')
  })

  it('devolve null quando a seção não existe', () => {
    expect(sectionBody(CHANGELOG, '9.9.9')).toBeNull()
  })
})

describe('releaseNotes', () => {
  it('usa a seção da versão quando ela existe', () => {
    expect(releaseNotes(CHANGELOG, '0.13.0')).toBe(
      '### Fixed\n\n- Diff windows show their first frame in the saved language.\n',
    )
  })

  it('cai para o Unreleased quando o patch automático não tem seção', () => {
    const notas = releaseNotes(CHANGELOG, '0.13.1')
    expect(notas).toContain('- Tour of the interface.')
    expect(notas.endsWith('\n')).toBe(true)
    expect(notas).not.toContain('Diff windows')
  })

  it('lança erro claro quando nem a versão nem o Unreleased existem', () => {
    expect(() => releaseNotes('# Changelog\n\n## [0.12.0] - 2026-11-10\n\n- Algo.\n', '0.13.1')).toThrow(
      /não tem a seção ## \[0\.13\.1\] nem ## \[Unreleased\]/,
    )
  })

  it('lança erro quando a seção da versão não tem bullet', () => {
    const vazio = CHANGELOG.replace('- Diff windows show their first frame in the saved language.', '')
    expect(() => releaseNotes(vazio, '0.13.0')).toThrow(/## \[0\.13\.0\].*nenhuma mudança/)
  })

  it('lança erro quando o Unreleased tem só "Nothing yet."', () => {
    const nada = CHANGELOG.replace('### Added\n\n- Tour of the interface.', '- Nothing yet.')
    expect(() => releaseNotes(nada, '0.13.1')).toThrow(/## \[Unreleased\].*nenhuma mudança/)
  })

  it('seção da versão vazia não cai para o Unreleased', () => {
    const vazio = CHANGELOG.replace('- Diff windows show their first frame in the saved language.', '')
    expect(() => releaseNotes(vazio, '0.13.0')).toThrow()
  })

  it('recusa versão que não é x.y.z', () => {
    expect(() => releaseNotes(CHANGELOG, 'v0.13.0')).toThrow(/Versão inválida/)
    expect(() => releaseNotes(CHANGELOG, '0.13')).toThrow(/Versão inválida/)
  })
})

