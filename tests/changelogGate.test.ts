describe('findForbidden: textos de usuário passam', () => {
  it.each(BONS)('passa "%s"', (texto) => {
    expect(findForbidden(texto)).toEqual([])
  })

  it('IA, AI e QA só valem em MAIÚSCULAS e palavra inteira', () => {
    expect(findForbidden('mais, ai, ia e qa em minúsculas ficam de fora')).toEqual([])
    expect(findForbidden('PRIMEIRO, CIDADE, AIRBAG e QAT não são siglas')).toEqual([])
  })

  it('CI e PR reprovam em qualquer caixa, mas só como palavra inteira', () => {
    expect(findForbidden('ci Ci cI PR pr Pr prs PRs').map((a) => a.rule)).toEqual(['ci', 'ci', 'ci', 'pr', 'pr', 'pr', 'pr', 'pr'])
    expect(findForbidden('ciclo, precisa, primeiro, cidade, prazo, spring')).toEqual([])
  })

  it('o sublinhado separa palavras: o termo atrás dele continua achado', () => {
    expect(findForbidden('claude_code e gate_way').map((a) => a.rule)).toEqual(['claude', 'gate'])
  })

  it('hash de commit exige dígito e letra a-f: palavras e números puros passam', () => {
    expect(findForbidden('added, deface, effaced, 20261111, 0.13.0, 2026-11-11, #ffffff')).toEqual([])
    expect(findForbidden('veja a1b2c3d4').map((a) => a.rule)).toEqual(['hash-commit'])
  })

  it('palavra escondida por largura diferente, ligadura ou invisível é achada (NFKC)', () => {
    expect(findForbidden('\uFF30\uFF32 em largura total').map((a) => a.rule)).toContain('pr')
    expect(findForbidden('pipe\u200Bline').map((a) => a.rule)).toEqual(['invisivel', 'pipeline'])
    expect(findForbidden('pipe\u200Bline')[0].match).toBe('U+200B')
  })
})

describe('findForbidden: localização e forma', () => {
  it('devolve a linha (a partir de 1), a regra e o trecho', () => {
    const texto = '- Bom.\n- Também bom.\n- Ruim por causa do #12.'
    expect(findForbidden(texto)).toEqual([{ line: 3, rule: 'numero-issue-pr', match: '#12' }])
  })

  it('pega termo dentro de crase, de qualquer caixa, e todas as ocorrências da linha', () => {
    const achados = findForbidden('- Use `PIPELINE` e `Workflow` aqui.')
    expect(achados.map((a) => a.rule)).toEqual(['pipeline', 'workflow'])
  })

  it('aceita fim de linha do Windows', () => {
    expect(findForbidden('- ok\r\n- #3\r\n').map((a) => a.line)).toEqual([2])
  })

  it('pega acento decomposto (NFD) da mesma forma que o composto', () => {
    expect(findForbidden('fábrica').map((a) => a.rule)).toEqual(['fabrica'])
  })

  it('texto vazio não reprova', () => {
    expect(findForbidden('')).toEqual([])
  })
})

