import { spawn } from 'node:child_process'
import { mkdtempSync, realpathSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'
import { commitMessages, findAttribution, gateProblems } from '../scripts/atribuicao-gate.mjs'

// Portão de atribuição de IA no CI (issue #254): confere as mensagens dos commits do PR e o corpo do PR com as mesmas
// regras do hook local (#252), cobrindo o que o hook não vê. As fixtures abaixo têm de conter os termos proibidos.

const script = fileURLToPath(new URL('../scripts/atribuicao-gate.mjs', import.meta.url))
const RODAPE = '_Generated by [Claude Code](https://claude.ai/code)_'

const regras = (texto: string) => findAttribution(texto).map(({ line, rule }) => `${line}:${rule}`)

describe('findAttribution: mensagens de commit', () => {
  it('trailer Co-Authored-By reprova (qualquer coautor, qualquer caixa)', () => {
    expect(regras('titulo\n\nCo-Authored-By: Alguem <a@b>')).toEqual(['3:trailer'])
    expect(regras('titulo\n\nco-authored-by: Outro <o@o>')).toEqual(['3:trailer'])
  })

  it('trailer Claude-Session reprova', () => {
    expect(regras('titulo\n\nClaude-Session: https://x/y')).toEqual(['3:trailer'])
  })

  it('mensagem sem trailer passa', () => {
    expect(findAttribution('corrige o gate\n\nporque sim\n')).toEqual([])
    expect(findAttribution('')).toEqual([])
  })

  it('prosa com Co-Authored-By entre crases e sem dois-pontos passa', () => {
    expect(findAttribution('barra `Co-Authored-By` e `Claude-Session` no commit')).toEqual([])
  })

  it('CRLF: trailer numa mensagem com \\r\\n reprova, com o número da linha original', () => {
    expect(regras('titulo\r\n\r\nCo-Authored-By: Z <z@z>\r\n')).toEqual(['3:trailer'])
    // CR sozinho (Mac antigo) também separa linhas.
    expect(regras('titulo\r\rClaude-Session: x')).toEqual(['3:trailer'])
  })

  it('"Generated with [Claude Code]" reprova como rodape', () => {
    expect(regras('feito\n\n🤖 Generated with [Claude Code](https://x)')).toEqual(['3:rodape'])
    expect(regras('Generated by [claude code]')).toEqual(['1:rodape'])
  })

  it('link claude.com/claude-code reprova como link-produto', () => {
    expect(regras('veja https://claude.com/claude-code')).toEqual(['1:link-produto'])
  })

  it('uma linha pode dar vários achados', () => {
    expect(regras('🤖 Generated with [Claude Code](https://claude.com/claude-code)')).toEqual([
      '1:rodape',
      '1:link-produto',
    ])
  })
})

describe('findAttribution: corpo de PR', () => {
  it('corpo legítimo com --- e o rodapé exato da plataforma no fim passa', () => {
    expect(findAttribution(`## Resumo\n\nRefs #254\n\n---\n${RODAPE}`)).toEqual([])
    // Sem os sublinhados, com espaço em volta e com CRLF.
    expect(findAttribution('Refs #254\r\n\r\n  Generated by [Claude Code](https://claude.ai/code)  \r\n')).toEqual([])
  })

  it('o rodapé exato não leva junto um achado verdadeiro: o link de sessão noutra linha reprova só ele', () => {
    const corpo = `Resumo\n\n---\n${RODAPE}\nhttps://claude.ai/code/session_abc`
    expect(regras(corpo)).toEqual(['5:link-sessao'])
  })

  it('só a linha exata é ignorada: o rodapé com texto a mais continua reprovando', () => {
    expect(regras(`${RODAPE} obrigado`)).toEqual(['1:rodape', '1:link-sessao'])
    expect(regras('texto _Generated by [Claude Code](https://claude.ai/code)_')).toEqual(['1:rodape', '1:link-sessao'])
  })

  it('link de sessão sozinho reprova', () => {
    expect(regras('https://claude.ai/code/session_abc')).toEqual(['1:link-sessao'])
  })
})

describe('gateProblems', () => {
  it('descreve commit e corpo por sha curto, linha e regra', () => {
    const sha = 'a'.repeat(40)
    const problemas = gateProblems({
      commits: [{ sha, message: 'x\n\nCo-Authored-By: A <a@b>' }],
      body: 'ok\nhttps://claude.ai/code/s',
    })
    expect(problemas).toEqual([`commit ${'a'.repeat(12)}: linha 3, regra trailer`, 'corpo do PR: linha 2, regra link-sessao'])
  })

  it('sem achados devolve lista vazia', () => {
    expect(gateProblems({ commits: [{ sha: 'b'.repeat(40), message: 'limpo' }], body: '' })).toEqual([])
  })

  it('nunca inclui o texto da linha (texto de fora viraria comando do workflow)', () => {
    const malicioso = 'Co-Authored-By: x %0A::error title=falso::injetado'
    const problemas = gateProblems({
      commits: [{ sha: 'c'.repeat(40), message: malicioso }],
      body: `${malicioso}\nclaude.ai/code ::set-output name=a::b`,
    })
    expect(problemas.length).toBe(3)
    for (const problema of problemas) {
      expect(problema).not.toContain('%0A')
      expect(problema).not.toContain('::')
      expect(problema).not.toContain('injetado')
      expect(problema).not.toContain('set-output')
    }
  })
})

// --- CLI e git de verdade --------------------------------------------------------------------------------------------

let dir = ''

// Processo assíncrono: no Git Bash do Windows a chamada síncrona segura o worker do vitest tempo suficiente para o RPC
// estourar (mesmo motivo de gate-atribuicao.test.ts). Não rejeita por status diferente de zero.
function executar(cmd: string, args: string[], opts: { cwd?: string; env?: Record<string, string> } = {}) {
  return new Promise<{ status: number | null; stdout: string; stderr: string }>((resolve) => {
    const filho = spawn(cmd, args, {
      cwd: opts.cwd,
      env: { ...process.env, ...opts.env },
      stdio: ['ignore', 'pipe', 'pipe'],
    })
    let stdout = ''
    let stderr = ''
    filho.stdout.setEncoding('utf8')
    filho.stderr.setEncoding('utf8')
    filho.stdout.on('data', (pedaco: string) => {
      stdout += pedaco
    })
    filho.stderr.on('data', (pedaco: string) => {
      stderr += pedaco
    })
    filho.on('error', (erro) => resolve({ status: null, stdout, stderr: stderr + erro.message }))
    filho.on('close', (status) => resolve({ status, stdout, stderr }))
  })
}

async function git(...args: string[]) {
  const r = await executar('git', ['-c', 'user.name=t', '-c', 'user.email=t@t', '-c', 'commit.gpgsign=false', ...args], {
    cwd: dir,
  })
  if (r.status !== 0) throw new Error(`git ${args.join(' ')} falhou: ${r.stderr}`)
  return r.stdout.trim()
}

const commitar = (mensagem: string) => git('commit', '--allow-empty', '-q', '-m', mensagem)
const cli = (base: string, head: string, env: Record<string, string> = {}) =>
  executar(process.execPath, [script, base, head], { cwd: dir, env: { PR_BODY: '', ...env } })

beforeAll(async () => {
  dir = realpathSync.native(mkdtempSync(join(tmpdir(), 'gittools-atribgate-')))
  await git('init', '-q')
})

afterAll(() => {
  rmSync(dir, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 })
})

describe('atribuicao-gate CLI num repositório git', () => {
  it('commit da base com trailer não é reavaliado; só o intervalo base..head conta', async () => {
    await commitar('antigo\n\nCo-Authored-By: Antigo <a@a>')
    const base = await git('rev-parse', 'HEAD')
    await commitar('limpo\n\nsem trailer')
    const head = await git('rev-parse', 'HEAD')

    expect((await commitMessages(base, head, { cwd: dir })).map((c) => c.sha)).toEqual([head])

    const r = await cli(base, head)
    expect(r.status).toBe(0)
    expect(r.stdout).toContain('1 commit(s)')
    expect(r.stdout).not.toContain('::error')
  })

  it('commit com trailer no intervalo reprova (sai 1, ::error e sha curto) e o corpo é conferido', async () => {
    const base = await git('rev-parse', 'HEAD')
    await commitar('sujo\n\nCo-Authored-By: Alguem <x@x>')
    const sujo = await git('rev-parse', 'HEAD')
    await commitar('limpo de novo')
    const head = await git('rev-parse', 'HEAD')

    const r = await cli(base, head)
    expect(r.status).toBe(1)
    expect(r.stdout).toContain('::error title=Atribuição de IA::')
    expect(r.stdout).toContain(`commit ${sujo.slice(0, 12)}: linha 3, regra trailer`)
    // O commit limpo do intervalo não é apontado.
    expect(r.stdout).not.toContain(head.slice(0, 12))
  })

  it('merge commit do intervalo também é conferido', async () => {
    const base = await git('rev-parse', 'HEAD')
    await git('checkout', '-q', '-b', 'lateral')
    await commitar('na lateral')
    await git('checkout', '-q', '-')
    await commitar('na principal')
    await git('merge', '--no-ff', '-q', '-m', 'merge\n\nClaude-Session: https://x/y', 'lateral')
    const merge = await git('rev-parse', 'HEAD')

    const r = await cli(base, merge)
    expect(r.status).toBe(1)
    expect(r.stdout).toContain(`commit ${merge.slice(0, 12)}: linha 3, regra trailer`)
  })

  it('PR_BODY com link de sessão reprova; com o rodapé exato da plataforma passa', async () => {
    const base = await git('rev-parse', 'HEAD')

    const sujo = await cli(base, base, { PR_BODY: 'feito\n\nhttps://claude.ai/code/session_abc' })
    expect(sujo.status).toBe(1)
    expect(sujo.stdout).toContain('corpo do PR: linha 3, regra link-sessao')

    const limpo = await cli(base, base, { PR_BODY: `feito\n\n---\n${RODAPE}` })
    expect(limpo.status).toBe(0)
    expect(limpo.stdout).toContain('corpo do PR conferido')
  })

  it('PR_BODY ausente conta como vazio', async () => {
    const head = await git('rev-parse', 'HEAD')
    const r = await executar(process.execPath, [script, head, head], { cwd: dir })
    expect(r.status).toBe(0)
    expect(r.stdout).toContain('corpo do PR vazio')
  })

  it('sha inválido sai 2, sem chamar o git com a opção', async () => {
    const head = await git('rev-parse', 'HEAD')
    const opcao = await cli('--foo', head)
    expect(opcao.status).toBe(2)
    expect(opcao.stderr).toContain('base inválido')
    expect((await cli(head, 'HEAD')).status).toBe(2)
    await expect(commitMessages('--output=x', head, { cwd: dir })).rejects.toThrow('base inválido')
  })

  it('uso errado (argumentos faltando) e sha que o git não conhece saem 2', async () => {
    const head = await git('rev-parse', 'HEAD')
    const semArgs = await executar(process.execPath, [script, head], { cwd: dir })
    expect(semArgs.status).toBe(2)
    expect(semArgs.stderr).toContain('Uso:')
    expect((await cli('deadbeef'.repeat(5), head)).status).toBe(2)
  })
})
