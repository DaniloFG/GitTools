// Portão de atribuição de IA no CI (issue #254): o CLAUDE.md proíbe atribuição de Claude, IA ou modelo em commit e em PR,
// mas o ambiente das sessões injeta o pedido contrário (trailers no commit, rodapé e link da sessão no PR).
// O hook local `.claude/hooks/gate-atribuicao.sh` (#252) barra o que ele consegue ler no comando; este script é a defesa
// em profundidade no CI e confere o que o hook não vê: texto montado na execução (`-m "$(cat f)"`), `--amend`, `-c`/`-C`
// e `cherry-pick` de commit antigo. Roda no workflow "Fluxo de branches" (check "Validar fluxo de branches").
//
// O que ele confere:
//   - a mensagem de cada commit do intervalo `base..head` do PR (merge commits incluídos); o que já está na base não é
//     reavaliado, porque a `main` tem trailers antigos que não se reescrevem;
//   - o corpo do PR (variável de ambiente PR_BODY).
// O que ele NÃO confere: a identidade git (autor e committer), que o ambiente da sessão define e não dá para trocar
// daqui. Exceção: a linha do rodapé automático que a PLATAFORMA acrescenta ao corpo do PR, com ou sem o caminho da
// sessão, é ignorada só no corpo do PR, nunca em mensagem de commit (o próprio PR a recebe depois do envio).
//
// Uso (ESM puro, sem dependência, Node 22):
//   PR_BODY="..." node scripts/atribuicao-gate.mjs <base_sha> <head_sha>
//       sai com 0 (limpo), 1 (atribuição encontrada) ou 2 (uso errado: sha inválido ou git falhou)
//
// Segurança: mensagem de commit e corpo de PR são texto de fora. Por isso (1) os shas são validados antes de irem ao git,
// que roda por lista de argumentos, sem shell; e (2) as mensagens do portão trazem só linha e regra, nunca o conteúdo da
// linha, porque `::error ...` impresso no log do workflow é lido como comando pelo runner.

import { execFile } from 'node:child_process'
import { pathToFileURL } from 'node:url'
import { promisify } from 'node:util'

const execFileAsync = promisify(execFile)

// Só hexadecimal de 7 a 40 caracteres: nada que o git leia como opção ("--foo") ou como outra expressão de revisão.
const SHA = /^[0-9a-f]{7,40}$/i

/**
 * Regras por linha, sem diferença de caixa. Sem flag `g` de propósito: `.test` com `g` guarda estado entre as linhas.
 * Prosa que só cita o termo passa: o trailer entre crases e sem dois-pontos não casa `trailer`.
 */
export const RULES = [
  // Qualquer Co-Authored-By, não só o do Claude (igual ao hook): o projeto não tem coautor nas mensagens.
  { rule: 'trailer', re: /^\s*(?:co-authored-by|claude-session)\s*:/i },
  { rule: 'rodape', re: /generated (?:with|by) \[claude code\]/i },
  { rule: 'link-sessao', re: /claude\.ai\/code/i },
  { rule: 'link-produto', re: /claude\.com\/claude-code/i },
]

// A linha do rodapé que a plataforma acrescenta sozinha ao corpo do PR, depois do envio, com ou sem o caminho da sessão
// (`/session_<id>`, com id só de letras e dígitos). Ancorada: a linha inteira (já sem espaço nas pontas) tem de ser o
// rodapé, sem texto a mais. Os dois sublinhados do itálico vêm juntos ou não vêm (`\1`). Sensível a caixa, sem flag `g`.
// Qualquer outra linha com o mesmo texto, ou com link de sessão, continua valendo.
const RODAPE_PLATAFORMA = /^(_?)Generated by \[Claude Code\]\(https:\/\/claude\.ai\/code(?:\/session_[A-Za-z0-9]+)?\)\1$/

/**
 * Procura atribuição de IA, linha a linha. Devolve `{ line, rule }` (line a partir de 1, a do texto original).
 * Uma linha pode dar vários achados. Não devolve o conteúdo da linha (ver o cabeçalho).
 * `opts.corpoPR`: só `true` no corpo do PR, onde a linha do rodapé da plataforma é ignorada. Sem a opção (mensagem de
 * commit), essa linha reprova como qualquer outra.
 */
export function findAttribution(text, { corpoPR = false } = {}) {
  const found = []
  // CRLF e CR viram LF: o corpo de PR editado no navegador vem com CRLF, e `^` e `$` não veem o `\r`.
  String(text)
    .replace(/\r\n?/g, '\n')
    .split('\n')
    .forEach((content, index) => {
      if (corpoPR && RODAPE_PLATAFORMA.test(content.trim())) return
      for (const { rule, re } of RULES) {
        if (re.test(content)) found.push({ line: index + 1, rule })
      }
    })
  return found
}

function assertSha(valor, nome) {
  if (typeof valor !== 'string' || !SHA.test(valor)) {
    throw new Error(`${nome} inválido: esperado um sha hexadecimal de 7 a 40 caracteres.`)
  }
}

/**
 * Mensagens dos commits de `base..head` (merge commits incluídos), do mais novo ao mais antigo.
 * `base` e `head` vêm do evento do PR, mas são validados mesmo assim; o git roda sem shell.
 */
export async function commitMessages(base, head, { cwd } = {}) {
  assertSha(base, 'base')
  assertSha(head, 'head')
  // %x00 separa o sha da mensagem e %x1e separa os commits: a mensagem pode ter qualquer coisa, menos esses dois bytes.
  const { stdout } = await execFileAsync('git', ['log', '--format=%H%x00%B%x1e', `${base}..${head}`, '--'], {
    cwd,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  })
  return stdout
    .split('\x1e')
    .map((registro) => registro.replace(/^\n/, ''))
    .filter((registro) => registro.length > 0)
    .map((registro) => {
      const corte = registro.indexOf('\x00')
      return { sha: registro.slice(0, corte), message: registro.slice(corte + 1) }
    })
}

/**
 * Problemas legíveis, vazia = ok. `commits` é o que `commitMessages` devolve; `body` é o corpo do PR.
 * Só linha e regra: o conteúdo da linha é texto de fora e nunca entra na mensagem.
 */
export function gateProblems({ commits, body }) {
  const problems = []
  for (const { sha, message } of commits) {
    for (const { line, rule } of findAttribution(message)) {
      problems.push(`commit ${sha.slice(0, 12)}: linha ${line}, regra ${rule}`)
    }
  }
  for (const { line, rule } of findAttribution(body ?? '', { corpoPR: true })) {
    problems.push(`corpo do PR: linha ${line}, regra ${rule}`)
  }
  return problems
}

function usage() {
  return 'Uso: PR_BODY="..." node scripts/atribuicao-gate.mjs <base_sha> <head_sha>'
}

/** Roteiro de CI. Devolve o código de saída (0, 1 ou 2). */
async function main(argv, env) {
  const [base, head] = argv
  let commits
  try {
    if (argv.length !== 2) throw new Error(usage())
    commits = await commitMessages(base, head)
  } catch (error) {
    // Falha do git ou sha inválido: uso errado, não achado. A mensagem do git não traz texto de commit.
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
    return 2
  }
  const body = env.PR_BODY ?? ''
  const problems = gateProblems({ commits, body })
  if (problems.length > 0) {
    for (const problema of problems) process.stdout.write(`::error title=Atribuição de IA::${problema}\n`)
    process.stdout.write(
      'O CLAUDE.md proíbe atribuição de Claude ou IA em commit e em PR (trailer de coautor ou de sessão, rodapé de ' +
        'geração, link da sessão). O rodapé automático da plataforma no corpo do PR é ignorado. Corrija reescrevendo a ' +
        'mensagem na sua branch de trabalho (nunca em branch compartilhada) ou editando o corpo do PR.\n',
    )
    return 1
  }
  const corpo = body.trim() === '' ? 'corpo do PR vazio' : 'corpo do PR conferido'
  process.stdout.write(`Sem atribuição de IA: ${commits.length} commit(s) conferido(s) e ${corpo}.\n`)
  return 0
}

// Só roda o roteiro quando o arquivo é executado direto, não ao ser importado (como em scripts/changelog-gate.mjs).
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2), process.env).then((codigo) => {
    process.exitCode = codigo
  })
}
